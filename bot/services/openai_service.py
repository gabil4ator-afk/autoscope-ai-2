from openai import AsyncOpenAI
from bot.config import OPENAI_API_KEY
import base64
import datetime

# Получаем реальный текущий год прямо сейчас (2026)
current_year = datetime.date.today().year 

# Вставляем его прямо в системный промт перед отправкой в OpenRouter
system_prompt = f"""
Ты — эксперт по автоподбору. 
ВНИМАНИЕ: Сейчас СТРОГО {current_year} год. 
Если машина 2019 года выпуска, то её возраст на данный момент составляет ровно {current_year} - 2019 = {current_year - 2019} лет!
Считай среднегодовой пробег только на основе этой цифры.
"""

TEXT_PROMPT = '''Ты — опытный эксперт по автоподбору со стажем 10 лет...
Риск + Надёжность = 100.
Если серьёзные вложения — оценка не выше 65.
Выдавай ответ строго по шаблону пользователя.
'''

VISION_PROMPT = '''Ты — эксперт по автоподбору и криминалист автомобильных объявлений. Перед тобой изображение.

### КРИТИЧЕСКОЕ ПРАВИЛО:
На изображении может быть скриншот экрана телефона с открытым приложением (например, Auto.ru, Avito, Drom). Твоя задача — игнорировать весь периферийный интерфейс: статус-бар телефона (время, батарея, сеть), заголовок Telegram-бота, кнопки Telegram. Найди на изображении *область, содержащую объявление*, и проанализируй именно её. Также объявление может быть представлено в виде нескольких фрагментов (коллажа) на одном изображении. Собери информацию по частям.

### ТВОЙ АНАЛИЗ (Фокусируйся на ядре объявления):
1. **Сбор данных:** Найди марку/модель, цену, пробег, год, количество владельцев. Считай их экспертно, игнорируя шум.
2. **Психология объявления:** Прочитай описание, если оно есть. Ищи фразы перекупов.
3. **Геолокация:** Где сфотографировано авто? Если на фоне авторынка, автосалона — это красный флаг.
4. **Скрытие данных:** Замазаны ли номера? Скрыт ли VIN?

### ПРАВИЛА РАСЧЕТА МЕТРИК:
- Сумма Риска и Надёжности строго равна 100%.
- Если обнаружены признаки серого салона, перекупа или замазанных номеров — Риск автоматически от 40%, Оценка не выше 60/100.
- Если цена подозрительно низкая для такого года и пробега — Риск от 30%.

Выдавай ответ СТРОГО по шаблону (маркдаун Telegram):

🏆 **Оценка:** [X]/100
📈 **Надёжность:** [X]%
⚠️ **Риск:** [X]%
💰 **Торг:** [X]% (краткое обоснование, например: "на замену сцепления")

🚩 **Красные флаги:**
• **[Визуальный или текстовый флаг]:** [Экспертное объяснение, почему это плохо].
• **[Флаг 2]:** [Объяснение].

🏁 **Вердикт:** [Краткое заключение на основе увиденного. Стоит ли покупать].

Если на изображении вообще нет информации об автомобиле (переписка, мем), ответь: "Ошибка: На изображении не обнаружено объявление о продаже автомобиля. Риск + Надёжность = 100."
ДОПОЛНИТЕЛЬНЫЕ ПРАВИЛА АНАЛИЗА ДЛЯ ИИ:
1. Расчет среднегодового пробега: Текущий год — 2026. Всегда вычитай из 2026 года год выпуска авто, чтобы узнать чистый возраст. Дели общий пробег на этот возраст. 
   - Если среднегодовой пробег больше 25 000 км — обязательно пиши в Красных флагах: "Риск использования в такси или коммерции".
2. Реалистичная оценка владельцев: 
   - 1-2 владельца за 5-7 лет — это отлично.
   - 3 владельца за 5-7 лет — это НОРМАЛЬНО, не пиши это в красные флаги.
   - 4+ владельца за любой срок — это красный флаг.
3. Избегай размытых фраз: Вместо "может указывать на проблемы" пиши конкретно, чем это грозит (например: "грозит дорогой капиталкой мотора", "потребует замены подвески" и т.д.).
КРИТИЧЕСКОЕ ПРАВИЛО ДЛЯ КОЛИЧЕСТВА ВЛАДЕЛЬЦЕВ:
- Если машине больше 5 лет, и у неё 3 владельца — это АБСОЛЮТНАЯ НОРМА рынка. Запрещено писать это в "Красные флаги" и снижать за это оценку.
- Заноси количество владельцев в "Красные флаги" только в двух случаях: 
  1) Если владельцев 4 и более.
  2) Если машина совсем свежая (ей 1-2 года), а у неё уже 3 владельца (маркер проблемного авто или перекупа).
  КРИТИЧЕСКОЕ ПРАВИЛО ВРЕМЕНИ (ВНИМАТЕЛЬНО):
- Текущий год — 2026. 
- Возраст автомобиля рассчитывается СТРОГО по формуле: 2026 минус [Год выпуска из объявления]. Никаких других цифр выдумывать нельзя.
- Срок владения для расчета «частой смены владельцев» равен возрасту автомобиля. Для машины 2019 года этот срок равен 7 годам. 3 владельца за 7 лет — это норма (в среднем по 2.3 года на человека). Это НЕ красный флаг! Не пиши про "частую продажу", если машине 7 лет.
'''

client = AsyncOpenAI(api_key=OPENAI_API_KEY, base_url="https://openrouter.ai/api/v1")

async def analyze_text(text):
    r = await client.chat.completions.create(
        model="google/gemini-2.5-flash",
        messages=[
            {"role":"system","content":TEXT_PROMPT},
            {"role":"user","content":text}
        ],
        max_tokens=700
    )
    return r.choices[0].message.content

async def analyze_images(image_paths):
    content=[{"type":"text","text":"Проанализируй все изображения как одно объявление"}]
    for p in image_paths:
        with open(p,"rb") as f:
            b64=base64.b64encode(f.read()).decode()
        content.append({"type":"image_url","image_url":{"url":f"data:image/jpeg;base64,{b64}"}})

    r = await client.chat.completions.create(
        model="openai/gpt-4o-mini",
        messages=[
            {"role":"system","content":VISION_PROMPT},
            {"role":"user","content":content}
        ],
        max_tokens=700
    )
    return r.choices[0].message.content
